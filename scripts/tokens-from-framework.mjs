// Shared values from the editor's own set of the techies.tools Framework (atomic catalogue, ticket 02).
//
//   node scripts/tokens-from-framework.mjs export   run the Framework's compiler on the committed settings and
//                                                    write src/tokens/framework-editor.css (needs TechiesTools)
//   node scripts/tokens-from-framework.mjs build    write the generated block of src/theme.css from that export
//   node scripts/tokens-from-framework.mjs check    fail when the block and the export disagree (no argument = check)
//
// `export` imports the Framework from FRAMEWORK_DIR (default ~/Projects/TechiesTools) and never writes there.
// `build` and `check` read only files of this repo, so CI and self-hosted copies can run them.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export const files = {
  settings: join(root, "src/tokens/framework-editor.settings.json"),
  exported: join(root, "src/tokens/framework-editor.css"),
  theme: join(root, "src/theme.css"),
};
export const startMark = "/* ---- generated by scripts/tokens-from-framework.mjs";
export const endMark = "/* ---- end generated ---- */";
const rootFontSize = 14;
const frameworkRemPx = 16;

const emptyCatalog = Object.freeze({ elements: Object.freeze([]), get: () => undefined, rule: () => undefined, group: () => Object.freeze([]) });

/** Compile the committed settings with the Framework's own export code and return its tokens.css. */
export async function exportTokens(settings, frameworkDir) {
  const compilerPath = join(frameworkDir, "src/framework/compiler/index.ts");
  if (!existsSync(compilerPath)) throw new Error(`Framework compiler not found at ${compilerPath} (set FRAMEWORK_DIR)`);
  const { compileFramework } = await import(pathToFileURL(compilerPath).href);
  const compilation = compileFramework({
    catalog: emptyCatalog,
    primitiveSnapshot: settings.snapshot,
    identity: settings.identity,
    sourceRevision: settings.sourceRevision,
    contextSchemaVersion: "2",
  });
  const tokens = compilation.artifacts.tokens;
  if (!tokens.available) throw new Error(`Framework refused the settings: ${tokens.diagnostics.map((item) => item.message).join(" ")}`);
  return tokens.value.value;
}

/** Custom properties of the export's :root, in order, plus the header's content hash. */
export function parseExport(css) {
  const hash = /Content hash: (\S+)/.exec(css)?.[1];
  if (!hash) throw new Error("export has no Content hash line");
  const body = /:root \{([^}]*)\}/.exec(css)?.[1];
  if (body === undefined) throw new Error("export has no :root block");
  const entries = [...body.matchAll(/(--[a-z0-9-]+):\s*([^;]+);/g)].map((match) => [match[1], match[2].trim()]);
  if (!entries.length) throw new Error("export has no custom properties");
  return { hash, entries };
}

const number = (value) => String(Number(value.toFixed(3)));
/** A Framework length in the editor's pixels: the Framework counts rem as 16px, the editor's root is 14px. */
export function toEditorPx(name, value) {
  const flat = /^(-?[\d.]+)rem$/.exec(value) ?? /^clamp\((-?[\d.]+)rem, calc\(\1rem \+ 0vw\), \1rem\)$/.exec(value);
  if (!flat) throw new Error(`${name}: ${value} is fluid or not in rem; the editor set must use manual mode with fixed sizes`);
  const rem = Number(flat[1]);
  // 999rem is the Framework's pill corner; any large corner is a pill, so it keeps the editor's 999px.
  return rem >= 99 ? "999px" : `${number(rem * frameworkRemPx)}px`;
}

export function generatedBlock(css) {
  const { hash, entries } = parseExport(css);
  const lines = entries.map(([name, value]) => `  ${name}: ${toEditorPx(name, value)};`);
  return [
    `${startMark} from src/tokens/framework-editor.css (content hash ${hash}) for the ${rootFontSize}px root.`,
    "   Do not edit by hand: change the settings, run `export` then `build` (docs/editor-colors.md). ---- */",
    ":root {",
    ...lines,
    "}",
    endMark,
  ].join("\n");
}

const blockPattern = new RegExp(`${startMark.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${endMark.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`);
export const currentBlock = (theme) => blockPattern.exec(theme)?.[0];
export const withBlock = (theme, block) => {
  if (!currentBlock(theme)) throw new Error("theme.css has no generated block markers");
  return theme.replace(blockPattern, () => block);
};

/** Problems with theme.css against the committed export; an empty list means in step. */
export function checkTheme(theme, css) {
  const found = currentBlock(theme);
  if (!found) return ["src/theme.css has no generated block; run `node scripts/tokens-from-framework.mjs build`"];
  return found === generatedBlock(css) ? [] : ["src/theme.css generated block differs from src/tokens/framework-editor.css; do not hand edit it, run `node scripts/tokens-from-framework.mjs build`"];
}

async function main(command) {
  if (command === "export") {
    const settings = JSON.parse(readFileSync(files.settings, "utf8"));
    const frameworkDir = process.env.FRAMEWORK_DIR ?? join(homedir(), "Projects/TechiesTools");
    writeFileSync(files.exported, await exportTokens(settings, frameworkDir));
    console.log(`wrote ${files.exported}`);
  } else if (command === "build") {
    writeFileSync(files.theme, withBlock(readFileSync(files.theme, "utf8"), generatedBlock(readFileSync(files.exported, "utf8"))));
    console.log(`wrote the generated block of ${files.theme}`);
  } else if (command === "check" || command === undefined) {
    const problems = checkTheme(readFileSync(files.theme, "utf8"), readFileSync(files.exported, "utf8"));
    for (const problem of problems) console.error(problem);
    console.log(problems.length ? `RESULT: fail tokens ${problems.length} problem` : "RESULT: ok tokens in step");
    if (problems.length) process.exitCode = 1;
  } else {
    console.error("usage: tokens-from-framework.mjs [export|build|check]");
    process.exitCode = 2;
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main(process.argv[2]);
