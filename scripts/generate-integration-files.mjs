import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const target = resolve(root, "worker/integration-files.ts");
const sourceRoot = resolve(root, "fixtures/astro-starter");
const files = [
  ".astro-editor/annotate.mjs",
  ".astro-editor/text-attributes.mjs",
  ".astro-editor/text-attributes.d.mts",
  ".astro-editor/text-options.mjs",
  ".astro-editor/text-options.d.mts",
  ".astro-editor/preview-alias.mjs",
  ".astro-editor/preview-alias.d.mts",
];

async function existingKnownHashes() {
  try {
    const current = await readFile(target, "utf8");
    const currentOfficial = /path:\s*"\.astro-editor\/annotate\.mjs",\s*sha256:\s*"([a-f0-9]{64})"/.exec(current)?.[1];
    const block = /knownOfficialAnnotateHashes\s*=\s*new Set\(\[([\s\S]*?)\]\)/.exec(current)?.[1] ?? "";
    return [
      ...(currentOfficial ? [currentOfficial] : []),
      ...[...block.matchAll(/"([a-f0-9]{64})"/g)].map((match) => match[1]),
    ];
  } catch {
    return [];
  }
}

function sha256(content) {
  return createHash("sha256").update(content).digest("hex");
}

const rows = [];
for (const path of files) {
  const content = await readFile(resolve(sourceRoot, path), "utf8");
  rows.push({ path, sha256: sha256(content), content });
}

const known = [...new Set(await existingKnownHashes())].filter(
  (hash) => hash !== rows[0].sha256,
);

let output = `// Latest server-owned Astro Site Editor integration files.\n`;
output += `// Generated by scripts/generate-integration-files.mjs from ${relative(root, sourceRoot)}/.astro-editor.\n\n`;
output += `export const integrationFiles = [\n`;
for (const row of rows)
  output += `  { path: ${JSON.stringify(row.path)}, sha256: ${JSON.stringify(row.sha256)}, content: ${JSON.stringify(row.content)} },\n`;
output += `] as const;\n\n`;
output += `export const knownOfficialAnnotateHashes = new Set([\n`;
output += `  integrationFiles[0].sha256,\n`;
for (const hash of known) output += `  ${JSON.stringify(hash)},\n`;
output += `]);\n`;

await writeFile(target, output);
